<?php
/**
 * AI-ассистент поддержки DesSega& на базе DeepSeek (OpenAI-совместимый API).
 *
 * Если DEEPSEEK_API_KEY не задан — бот работает на встроенных правилах
 * (ai_fallback), страница поддержки при этом остаётся функциональной.
 */
require_once __DIR__ . '/../config.php';

/** Есть ли ключ и функции HTTP для обращения к DeepSeek */
function ai_available(): bool {
    return defined('DEEPSEEK_API_KEY') && DEEPSEEK_API_KEY !== ''
        && function_exists('curl_init');
}

/** Системный промпт: кто бот и что он знает */
function ai_system_prompt(): string {
    return <<<PROMPT
Ты — Сегочка, AI-помощник службы доставки продуктов DesSega& из Нефтеюганска.
Отвечай на русском языке, дружелюбно, кратко (2-5 предложений), без markdown-разметки.

Факты о сервисе:
- DesSega& доставляет продукты из сети «Магнит» по Нефтеюганску.
- Средняя доставка — 45 минут, приём заказов 24/7, доставка по городу бесплатная.
- Оплата — по QR СБП (около 10 секунд), карта и наличные пока в разработке.
- В каталоге 31+ товар: молочка, хлеб, мясо, фрукты, напитки, сладости.
- Скидки партнёра до 30% подсвечиваются в каталоге автоматически.
- Часы живых операторов: Пн-Пт 9:00-18:00, телефон 8 (3463) 00-00-00, почта info@dessega.ru, Telegram @dessega_support.
- Среднее время ответа модератора — до 24 часов.
- Статусы заказа: «Ожидает оплаты», «Оплачен · собираем», «Доставлен». Отменить заказ можно до статуса «собираем».
- Проект демо: реальные списания, SMS и пуш-уведомления отключены.

Правила:
1. Отвечай только про DesSega& и доставку продуктов. На посторонние темы вежливо
   отказывай и предлагай вернуться к вопросам сервиса.
2. Если вопрос требует человека (претензия, возврат денег, жалоба на курьера) —
   скажи, что передал обращение модератору, они ответят в течение 24 часов.
3. Никогда не выдумывай цены и акции — ориентируйся на каталог сайта.
PROMPT;
}

/**
 * Запрос к DeepSeek Chat Completions.
 * @param array $history  массив сообщений [['role'=>'user'|'assistant','content'=>string], ...]
 * @return string|null    ответ ассистента или null при ошибке
 */
function ai_chat(array $history): ?string {
    if (!ai_available()) return null;

    // бережём контекст: не более 12 последних сообщений
    $history = array_slice($history, -12);
    $messages = array_merge(
        [['role' => 'system', 'content' => ai_system_prompt()]],
        $history
    );

    $payload = json_encode([
        'model'       => DEEPSEEK_MODEL,
        'messages'    => $messages,
        'temperature' => 0.6,
        'max_tokens'  => 350,
    ], JSON_UNESCAPED_UNICODE);

    $ch = curl_init(DEEPSEEK_API_URL);
    curl_setopt_array($ch, [
        CURLOPT_POST           => true,
        CURLOPT_POSTFIELDS     => $payload,
        CURLOPT_RETURNTRANSFER => true,
        CURLOPT_TIMEOUT        => 20,
        CURLOPT_CONNECTTIMEOUT => 7,
        CURLOPT_HTTPHEADER     => [
            'Content-Type: application/json',
            'Authorization: Bearer ' . DEEPSEEK_API_KEY,
        ],
    ]);
    $body = curl_exec($ch);
    $status = (int)curl_getinfo($ch, CURLINFO_HTTP_CODE);
    curl_close($ch);

    if ($body === false || $status !== 200) return null;
    $data = json_decode((string)$body, true);
    $reply = $data['choices'][0]['message']['content'] ?? null;
    $reply = is_string($reply) ? trim($reply) : null;
    return ($reply !== null && $reply !== '') ? $reply : null;
}

/** Ответ без API — по ключевым словам обращения */
function ai_fallback(string $text): string {
    $t = mb_strtolower($text, 'UTF-8');
    $rules = [
        ['/(привет|здравств|добрый|салат)/u',
            'Здравствуйте! Я Сегочка, помощник DesSega&. Расскажите, что случилось — по заказу, доставке или оплате — и я подскажу решение.'],
        ['/(где|статус|долг[оа]|долго|едет|задерж)/u',
            'Посмотреть статус заказа можно в личном кабинете во вкладке «Мои заказы». Если доставка задерживается больше чем на час — напишите, я передам обращение модератору.'],
        ['/(отмен|верн[уи]|возврат|деньг[ие]|верните)/u',
            'Заказ можно отменить до статуса «собираем» — кнопкой в личном кабинете. Для возврата средств оставьте номер заказа, я передал обращение модератору, он ответит в течение 24 часов.'],
        ['/(оплат|спб|сбп|карт|qr|квитанц)/u',
            'Оплата принимается по QR СБП — это занимает около 10 секунд в приложении банка. Карта и наличные появятся позже. Если списание прошло, а заказ не оплачен — напишите, разберёмся.'],
        ['/(доставк|курьер|время|час)/u',
            'Средняя доставка — 45 минут по Нефтеюганску, бесплатно. Приём заказов 24/7, курьеры работают ежедневно. Интервал доставки выбирается при оформлении заказа.'],
        ['/(скидк|акци|промокод|подешев)/u',
            'Скидки партнёра «Магнит» до 30% подсвечены в каталоге зачёркнутой ценой. Промокоды применяются автоматически в корзине.'],
        ['/(телефон|позвон|контакт|почт|telegram)/u',
            'Связаться с людьми: 8 (3463) 00-00-00, почта info@dessega.ru, Telegram @dessega_support. Часы операторов: Пн-Пт 9:00-18:00.'],
        ['/(курьер|хочу работать|ваканс|подработ)/u',
            'Мы набираем курьеров! Заполните анкету на странице «Вакансии» — с вами свяжутся после проверки документов.'],
    ];
    foreach ($rules as [$pattern, $reply]) {
        if (preg_match($pattern, $t)) return $reply;
    }
    return 'Спасибо за обращение! Я записала ваш вопрос и передала модератору — они ответят в течение 24 часов. Если вопрос срочный, позвоните: 8 (3463) 00-00-00.';
}

/**
 * Единая точка входа: ответ бота с учётом истории диалога.
 * Сначала пробуем DeepSeek, при недоступности — локальные правила.
 */
function ai_support_reply(string $userText, array $history = []): string {
    $history[] = ['role' => 'user', 'content' => $userText];
    $reply = ai_chat($history);
    return $reply ?? ai_fallback($userText);
}
